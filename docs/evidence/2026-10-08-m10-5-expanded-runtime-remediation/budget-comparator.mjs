function copyData(input, path = [], ancestors = new Set) {
  if (input === null || typeof input === "string" || typeof input === "boolean" || typeof input === "number")
    return input;
  if (typeof input !== "object")
    throw new DataIssue(path, "Expected plain serializable data");
  if (path.length >= MAX_DATA_DEPTH)
    throw new DataIssue(path, `Data exceeds ${MAX_DATA_DEPTH} nested containers`);
  if (ancestors.has(input))
    throw new DataIssue(path, "Cyclic data is not supported");
  const array = Array.isArray(input);
  const prototype = Object.getPrototypeOf(input);
  if (array ? prototype !== Array.prototype : prototype !== Object.prototype && prototype !== null) {
    throw new DataIssue(path, "Expected a plain record or array");
  }
  ancestors.add(input);
  try {
    const output = array ? [] : Object.create(null);
    const keys = Reflect.ownKeys(input);
    const length = array ? Object.getOwnPropertyDescriptor(input, "length")?.value : 0;
    if (array && keys.length !== length + 1)
      throw new DataIssue(path, "Expected a dense undecorated array");
    for (const key of keys) {
      if (array && key === "length")
        continue;
      if (typeof key !== "string")
        throw new DataIssue(path, "Symbol fields are not supported");
      const index = array ? Number(key) : key;
      if (array && (!Number.isSafeInteger(index) || Number(index) < 0 || Number(index) >= length || String(index) !== key)) {
        throw new DataIssue(path, "Expected a dense undecorated array");
      }
      const nextPath = [...path, index];
      const descriptor = Object.getOwnPropertyDescriptor(input, key);
      if (!descriptor || !("value" in descriptor) || descriptor.enumerable !== true) {
        throw new DataIssue(nextPath, "Expected an own enumerable data field");
      }
      Object.defineProperty(output, key, { value: copyData(descriptor.value, nextPath, ancestors), enumerable: true, writable: true, configurable: true });
    }
    return output;
  } finally {
    ancestors.delete(input);
  }
}
