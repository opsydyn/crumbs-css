function extractBaselineSamples(selector, evidence) {
  if (selector === "effect.runtime.cjs.graph-bytes") {
    const data = evidence;
    const entries = data.results.filter((entry) => entry.scenario === "runtime" && entry.format === "cjs");
    const value = unique(entries.map((entry) => entry.graph.bytes));
    return Array.from({ length: Math.max(...entries.map((entry) => entry.samples.length)) }, () => value);
  }
  const runtimeGraph = selector.match(/^runtime\.(theme-core|tokens|theme-compatibility)\.(esm|cjs)\.graph-bytes$/);
  if (runtimeGraph) {
    const data = evidence;
    const scope = runtimeGraph[1];
    const format = runtimeGraph[2];
    const entrypoint = scope === "theme-compatibility" ? "theme" : scope;
    const graph = data.currentGraphs[entrypoint]?.[format];
    if (!graph)
      throw Error(`Missing runtime graph scenario: ${selector}`);
    return numbers(graph.samples);
  }
  const runtimeInit = selector.match(/^runtime-init\.(floor|current)\.(esm|cjs)\.load-ms\.median$/);
  if (runtimeInit) {
    const data = evidence;
    const scenario = data.scenarios.find((entry) => entry.runtime === runtimeInit[1] && entry.format === runtimeInit[2]);
    if (!scenario)
      throw Error(`Missing runtime initialization scenario: ${selector}`);
    return numbers(scenario.samples.map((sample) => sample.loadMs));
  }
  if (selector === "benchmark.cold-transform.max-median-ms" || selector === "benchmark.warm-transform.max-median-ms") {
    const data = evidence;
    const prefix = selector.includes(".cold-") ? "first transform " : "warm transform ";
    return maximaByRepetition(data.results.filter((entry) => entry.name.startsWith(prefix)).map((entry) => entry.runBatchMeanP50Ms));
  }
  if (selector === "metro-incremental.direct-css-edit-ms.median")
    return admitMetroIncrementalReport(evidence);
  const data = evidence;
  const compiler = selector.match(/^editor\.(tsc|tsgo)\.10000\.(wall-ms|memory-kib|instantiations)(?:\.median)?$/);
  if (compiler) {
    const runs = data.compilerRuns.filter((entry) => entry.engine === compiler[1] && entry.scale === 1e4);
    const values = runs.map((entry) => compiler[2] === "wall-ms" ? entry.wallMs : compiler[2] === "memory-kib" ? entry.diagnostics.memoryKiB : entry.diagnostics.instantiations);
    return numbers(values);
  }
  const completion = selector.match(/^editor\.10000\.(first|warm)-completion-ms\.median$/);
  if (completion) {
    const key = completion[1] === "first" ? "firstCompletionMs" : "warmCompletionMs";
    return numbers(data.completionRuns.filter((entry) => entry.scale === 1e4).map((entry) => entry[key]));
  }
  throw Error(`Unsupported baseline selector: ${selector}`);
}
function evidenceForSelector(selector, evidence) {
  if (selector.startsWith("effect."))
    return evidence.effect;
  if (selector.startsWith("runtime.") && selector.endsWith(".graph-bytes"))
    return evidence.runtimeGraph;
  if (selector.startsWith("runtime-init."))
    return evidence.runtimeInit;
  if (selector.startsWith("benchmark."))
    return evidence.benchmark;
  if (selector.startsWith("metro-incremental."))
    return evidence.incremental;
  return evidence.editor;
}
function comparisonIdentity(selector, evidence) {
  if (selector.startsWith("effect.")) {
    const data = evidence;
    return {
      environment: { environment: {
        effect: data.effect,
        platform: data.environment.platform,
        architecture: data.environment.architecture,
        nodes: [...new Set(data.results.flatMap((entry) => entry.samples.map((sample) => sample.node)))].sort()
      } },
      measurement: { build: data.build, protocol: data.protocol }
    };
  }
  if (selector.startsWith("runtime.") && selector.endsWith(".graph-bytes")) {
    const data = evidence;
    const environment = data.environment;
    return {
      environment: {
        bun: environment.bun,
        npm: environment.npm,
        platform: environment.platform,
        architecture: environment.architecture,
        osRelease: environment.osRelease,
        buildTool: environment.buildTool
      },
      measurement: { protocol: data.protocol, selector }
    };
  }
  if (selector.startsWith("runtime-init.")) {
    const data = evidence;
    return {
      environment: { environment: {
        platform: data.environment.platform,
        architecture: data.environment.architecture,
        osRelease: data.environment.osRelease,
        cpu: data.environment.cpu,
        nodes: data.scenarios.map((scenario) => ({ runtime: scenario.runtime, format: scenario.format, node: scenario.node }))
      } },
      measurement: { protocol: data.protocol, repetitions: data.environment.repetitions }
    };
  }
  if (selector.startsWith("benchmark.")) {
    const data = evidence;
    const protocol = { ...data.protocol };
    const coldTransform = selector === "benchmark.cold-transform.max-median-ms";
    const warmTransform = selector === "benchmark.warm-transform.max-median-ms";
    const legacyOrdering = "Sequential scenarios in listed order; warmup excluded; filesystem caches uncontrolled";
    const currentOrdering = "Sequential scenarios in listed order; warmup excluded; cold and warm transforms use the same fixture-root process cwd; fixture paths are package-relative; filesystem caches uncontrolled";
    const packageRootWarmOrdering = "Sequential scenarios in listed order; warmup excluded; cold transforms use fixture-root cwd; warm transforms use package-root cwd; fixture paths are package-relative; filesystem caches uncontrolled";
    const warmCwdMode = protocol.warmTransformCwd;
    if (warmTransform && warmCwdMode === "package-root" && protocol.ordering === packageRootWarmOrdering) {
      protocol.ordering = legacyOrdering;
      delete protocol.warmTransformCwd;
    }
    const coldOrderingMatches = protocol.ordering === legacyOrdering || protocol.ordering === currentOrdering || warmCwdMode === "package-root" && protocol.ordering === packageRootWarmOrdering;
    if (coldTransform && coldOrderingMatches) {
      if (warmCwdMode === "fixture-root" && protocol.ordering === currentOrdering || warmCwdMode === "package-root" && protocol.ordering === packageRootWarmOrdering) {
        delete protocol.warmTransformCwd;
      }
      protocol.ordering = "cold-transform-sequential-v1";
    }
    return {
      environment: { environment: data.environment },
      measurement: {
        protocol,
        fixtures: data.fixtures.map((fixture) => ({ ...fixture, file: normalizeBenchmarkFixturePath(fixture.file) })),
        scenarios: data.results.map(({ name, sampleKind, iterationsPerSample, warmupIterations, samplesPerRun }) => ({ name, sampleKind, iterationsPerSample, warmupIterations, samplesPerRun }))
      }
    };
  }
  if (selector.startsWith("metro-incremental.")) {
    const data = evidence;
    const fixture = data.measurementFixture ?? {
      entrySha256: data.fixture.entrySha256,
      styleSha256: data.fixture.originalStyleSha256,
      tokenSha256: data.fixture.originalTokenSha256,
      baseStyleSha256: data.fixture.originalBaseStyleSha256,
      workspaceTokenSha256: data.fixture.originalWorkspaceTokenSha256
    };
    return { environment: { environment: data.environment }, measurement: { protocol: data.protocol, fixture } };
  }
  const identity = evidence.identity;
  return {
    environment: { identity: {
      bun: identity.bun,
      node: identity.node,
      platform: identity.platform,
      arch: identity.arch,
      osRelease: identity.osRelease,
      cpuModel: identity.cpuModel,
      logicalCpus: identity.logicalCpus,
      totalMemoryBytes: identity.totalMemoryBytes,
      typescript: identity.typescript,
      tsgo: identity.tsgo
    } },
    measurement: {
      protocol: evidence.protocol,
      scales: evidence.manifest.scales.map(({ tokenCount, sourceSha256, sourceBytes, sourceLines }) => ({ tokenCount, sourceSha256, sourceBytes, sourceLines }))
    }
  };
}
function normalizeBenchmarkFixturePath(file) {
  const normalized = file.replaceAll("\\", "/");
  const packageMarker = "/packages/css/";
  const packageIndex = normalized.lastIndexOf(packageMarker);
  if (packageIndex >= 0)
    return normalized.slice(packageIndex + packageMarker.length);
  const relativePackagePrefix = "packages/css/";
  if (normalized.startsWith(relativePackagePrefix))
    return normalized.slice(relativePackagePrefix.length);
  return normalized;
}
function differingPaths(expected, actual, path = "") {
  if (Object.is(expected, actual))
    return [];
  if (Array.isArray(expected) && Array.isArray(actual)) {
    const differences = expected.length === actual.length ? [] : [`${path}.length`];
    for (let index = 0;index < Math.min(expected.length, actual.length); index += 1) {
      differences.push(...differingPaths(expected[index], actual[index], `${path}[${index}]`));
    }
    return differences;
  }
  if (isRecord(expected) && isRecord(actual)) {
    const differences = [];
    for (const key of [...new Set([...Object.keys(expected), ...Object.keys(actual)])].sort()) {
      differences.push(...differingPaths(expected[key], actual[key], path ? `${path}.${key}` : key));
    }
    return differences;
  }
  return [path || "$"];
}
function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
function numbers(values) {
  if (values.length === 0 || values.some((value) => typeof value !== "number" || !Number.isFinite(value)))
    throw Error("Evidence selector did not produce finite numbers");
  return values;
}
function median(values) {
  const sorted = numbers(values).sort((left, right) => left - right);
  return sorted[Math.floor(sorted.length / 2)];
}
function maximaByRepetition(series) {
  if (series.length === 0 || new Set(series.map((values) => values.length)).size !== 1)
    throw Error("Evidence series are absent or have unequal repetition counts");
  return series[0].map((_, index) => Math.max(...series.map((values) => values[index])));
}
function summarizeEnvelope(values) {
  const valid = numbers(values), middle = median(valid), min = Math.min(...valid), max = Math.max(...valid);
  const maxDeviationPercent = middle === 0 ? 0 : Math.max(Math.abs(min - middle), Math.abs(max - middle)) / Math.abs(middle) * 100;
  return { min, median: middle, max, maxDeviationPercent };
}
function roundUpToFive(value) {
  return Math.ceil(value / 5) * 5;
}
function unique(values) {
  const valid = numbers(values);
  if (new Set(valid).size !== 1)
    throw Error("Evidence selector did not produce one stable value");
  return valid[0];
}
